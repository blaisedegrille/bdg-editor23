import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const workspace = fileURLToPath(new URL('../', import.meta.url));
const fields = [
  'apiKey', 'authDomain', 'projectId', 'storageBucket',
  'messagingSenderId', 'appId', 'measurementId',
];
const required = ['apiKey', 'authDomain', 'projectId', 'appId'];

export function generateFirebaseEnvironment({
  root = workspace,
  configJson = process.env.FIREBASE_WEB_CONFIG,
  strict = false,
} = {}) {
  const target = resolve(root, 'src/environments/environment.ts');
  const local = resolve(root, 'firebase.web-config.local.json');
  const input = configJson !== undefined
    ? configJson
    : existsSync(local) ? readFileSync(local, 'utf8') : undefined;

  if (input === undefined) {
    if (strict) throw new Error('Missing FIREBASE_WEB_CONFIG or firebase.web-config.local.json.');
    if (existsSync(target)) return 'Existing Firebase environment preserved.';
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, readFileSync(resolve(root, 'src/environments/environment.example.ts')),
      { mode: 0o600 });
    return 'WARNING: using example Firebase config; authentication and cloud storage will not work.';
  }

  let config;
  try {
    config = JSON.parse(input);
  } catch {
    // Never include the input or JSON parser error (which can expose values).
    throw new Error('Firebase web config must be valid JSON.');
  }
  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    throw new Error('Firebase web config must be a JSON object.');
  }
  for (const field of fields) {
    const value = config[field];
    if ((required.includes(field) && (typeof value !== 'string' || !value.trim())) ||
        (value !== undefined && typeof value !== 'string')) {
      throw new Error(`Invalid Firebase config field: ${field}.`);
    }
    if (strict && typeof value === 'string' && /EXAMPLE_|REDACTED_|YOUR_|^example(?:\.|$)/i.test(value)) {
      throw new Error(`Placeholder Firebase config field: ${field}.`);
    }
  }
  // Allow-list browser config fields: never copy a service-account private key.
  const firebase = Object.fromEntries(fields.filter((field) => config[field] !== undefined)
    .map((field) => [field, config[field]]));
  const content = `// Generated by scripts/generate-firebase-env.mjs. Do not commit.\n` +
    `import type { FirebaseOptions } from 'firebase/app';\n\n` +
    `export const environment = {\n  firebase: ${JSON.stringify(firebase, null, 2)} satisfies FirebaseOptions,\n};\n`;
  mkdirSync(dirname(target), { recursive: true });
  if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
    writeFileSync(target, content, { mode: 0o600 });
  }
  return 'Firebase environment generated (values not logged).';
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  try {
    console.log(generateFirebaseEnvironment({ strict: process.argv.includes('--strict') }));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
